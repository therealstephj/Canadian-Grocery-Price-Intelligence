CREATE TABLE IF NOT EXISTS dim_date(
	date_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	date DATE NOT NULL UNIQUE,
	year SMALLINT NOT NULL,
	month SMALLINT NOT NULL,
	quarter SMALLINT NOT NULL,
    CONSTRAINT dim_date_first_day_check CHECK (EXTRACT(DAY FROM date) = 1),
	CONSTRAINT dim_date_month_check CHECK (month BETWEEN 1 AND 12),
	CONSTRAINT dim_date_quarter_check CHECK (quarter BETWEEN 1 AND 4),
	CONSTRAINT dim_date_year_matches_date_check
        CHECK (year = EXTRACT(YEAR FROM date)::INTEGER),
    CONSTRAINT dim_date_month_matches_date_check
        CHECK (month = EXTRACT(MONTH FROM date)::INTEGER),
    CONSTRAINT dim_date_quarter_matches_date_check
        CHECK (quarter = EXTRACT(QUARTER FROM date)::INTEGER)
);

CREATE TABLE IF NOT EXISTS dim_geography (
    geography_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province VARCHAR(100) NOT NULL UNIQUE,
    province_code CHAR(2) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dim_product (
    product_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    unit VARCHAR(100) NOT NULL,
    CONSTRAINT dim_product_product_unit_unique UNIQUE (product, unit)
);

CREATE TABLE IF NOT EXISTS fact_price (
    date_key INTEGER NOT NULL,
    geography_key INTEGER NOT NULL,
    product_key INTEGER NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fact_price_pk PRIMARY KEY (date_key, geography_key, product_key),
    CONSTRAINT fact_price_date_fk FOREIGN KEY (date_key)
        REFERENCES dim_date (date_key),
    CONSTRAINT fact_price_geography_fk FOREIGN KEY (geography_key)
        REFERENCES dim_geography (geography_key),
    CONSTRAINT fact_price_product_fk FOREIGN KEY (product_key)
        REFERENCES dim_product (product_key),
    CONSTRAINT fact_price_nonnegative_check CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS fact_cpi (
    date_key INTEGER NOT NULL,
    geography_key INTEGER NOT NULL,
    cpi_group VARCHAR(150) NOT NULL,
    cpi_value NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fact_cpi_pk PRIMARY KEY (date_key, geography_key, cpi_group),
    CONSTRAINT fact_cpi_date_fk FOREIGN KEY (date_key)
        REFERENCES dim_date (date_key),
    CONSTRAINT fact_cpi_geography_fk FOREIGN KEY (geography_key)
        REFERENCES dim_geography (geography_key),
    CONSTRAINT fact_cpi_nonnegative_chk CHECK (cpi_value >= 0)
);

CREATE TABLE IF NOT EXISTS fact_forecast(
    date_key INTEGER NOT NULL,
    geography_key INTEGER NOT NULL,
    product_key INTEGER NOT NULL,
    
    model VARCHAR(100) NOT NULL,
    model_label VARCHAR(150),
    is_headline BOOLEAN NOT NULL DEFAULT FALSE,
    horizon_months SMALLINT NOT NULL,

    forecast NUMERIC(12, 2) NOT NULL,
    lower_80 NUMERIC(12, 2),
    upper_80 NUMERIC(12, 2),

    latest_price NUMERIC(12, 2),
    change_vs_latest_pct NUMERIC(12, 2),

    backtest_mae NUMERIC(12, 2),
    backtest_rmse NUMERIC(12, 2),
    backtest_mape_pct NUMERIC(12, 2),

    CONSTRAINT fact_forecast_pk PRIMARY KEY (date_key, geography_key, product_key, model)
    CONSTRAINT fact_forecast_date_fk FOREIGN KEY (date_key) 
        REFERENCES dim_date (date_key),
    CONSTRAINT fact_forecast_geography_fk FOREIGN KEY (geography_key) 
        REFERENCES dim_geography (geography_key),
    CONSTRAINT fact_forecast_product_fk FOREIGN KEY (product_key) 
        REFERENCES dim_product (product_key)
    CONSTRAINT fact_forecast_horizon_check CHECK (horizon_months > 0),
    CONSTRAINT fact_forecast_nonnegative_check CHECK (forecast >= 0),
    CONSTRAINT fact_forecast_interval_check
        CHECK (
            (lower_80 IS NULL OR lower_80 >= 0)
            AND (upper_80 IS NULL OR upper_80 >= 0)
            AND (
                lower_80 IS NULL
                OR upper_80 IS NULL
                OR lower_80 <= upper_80
            )
        )
);

-- Supporting indexes for joins
CREATE INDEX IF NOT EXISTS fact_price_geography_index
    ON fact_price (geography_key);
CREATE INDEX IF NOT EXISTS fact_price_product_index
    ON fact_price (product_key);
CREATE INDEX IF NOT EXISTS fact_cpi_geography_index
    ON fact_cpi (geography_key);
CREATE INDEX IF NOT EXISTS fact_forecast_geography_index
    ON fact_forecast (geography_key);
CREATE INDEX IF NOT EXISTS fact_forecast_product_index
    ON fact_forecast (product_key);

COMMIT;